# Step 3: Define helper function
def handle_outliers_auto(df, col, outlier_threshold=0.005):
    data = df[col]
    skewness = skew(data.dropna())

    if abs(skewness) > 0.75:
        # Use IQR method for skewed data
        Q1 = data.quantile(0.25)
        Q3 = data.quantile(0.75)
        IQR = Q3 - Q1
        lower_bound = Q1 - 1.5 * IQR
        upper_bound = Q3 + 1.5 * IQR
    else:
        # Use Z-score method for near-normal
        mean = data.mean()
        std = data.std()
        lower_bound = mean - 3 * std
        upper_bound = mean + 3 * std

    outliers = (data < lower_bound) | (data > upper_bound)
    outlier_pct = outliers.mean()

    if outlier_pct < outlier_threshold:
        # Drop outliers
        df = df[~outliers]
        action = "trimmed"
    else:
        # Cap the values
        df[col] = np.where(data < lower_bound, lower_bound,
                  np.where(data > upper_bound, upper_bound, data))
        action = "capped"

    print(f"{col}: {action} ({outlier_pct:.2%} outliers)")
    return df

