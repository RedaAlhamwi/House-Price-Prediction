class CountEncoder:
    def __init__(self, features):
        self.features = features
        self.count_dicts = {}

    def fit(self, df):
        for feature in self.features:
            self.count_dicts[feature] = df[feature].value_counts().to_dict()
        return self

    def transform(self, df):
        df = df.copy()
        for feature in self.features:
            df[f'{feature}_count'] = df[feature].map(self.count_dicts[feature]).fillna(0)
        return df

