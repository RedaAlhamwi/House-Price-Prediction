# =============================================================================
# STEP 3: Frequency Encoding
# =============================================================================
class FrequencyEncoder:
    def __init__(self, features):
        self.features = features
        self.freq_dicts = {}

    def fit(self, df):
        for feature in self.features:
            self.freq_dicts[feature] = (df[feature].value_counts() / len(df)).to_dict()
        return self

    def transform(self, df):
        df = df.copy()
        for feature in self.features:
            df[f'{feature}_freq'] = df[feature].map(self.freq_dicts[feature]).fillna(0)
        return df

