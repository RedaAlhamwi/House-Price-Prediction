# ======================================================
# AMES HOUSING PRICE PREDICTION - FEATURE ANALYSIS SCRIPT
# This script performs comprehensive feature analysis to:
# 1. Identify important numerical features using robust correlation methods
# 2. Analyze categorical features using ANOVA
# 3. Visualize key relationships and potential outliers
# ======================================================

from sklearn.feature_selection import mutual_info_regression
from scipy.stats import spearmanr, kendalltau, f_oneway, kruskal
from statsmodels.stats.multicomp import pairwise_tukeyhsd
import warnings

warnings.filterwarnings("ignore")

def compute_mic(X, y):
    """Compute MIC using mutual information as a proxy."""
    return mutual_info_regression(X, y, discrete_features=False)

def numerical_feature_scores(df, target):
    numerical_cols = df.select_dtypes(include=[np.number]).drop(columns=[target], errors='ignore').columns
    results = []
    for col in numerical_cols:
        if df[col].isnull().sum() > 0:
            continue
        pearson = df[col].corr(df[target], method='pearson')
        spearman = spearmanr(df[col], df[target])[0]
        kendall = kendalltau(df[col], df[target])[0]
        mic = compute_mic(df[[col]], df[target])[0]
        results.append({
            'feature': col,
            'pearson': pearson,
            'spearman': spearman,
            'kendall': kendall,
            'mic': mic
        })
    score_df = pd.DataFrame(results)
    score_df['robust_score'] = (0.4 * score_df['spearman'] +
                                0.3 * score_df['kendall'] +
                                0.3 * score_df['mic'])
    return score_df.sort_values(by='robust_score', ascending=False)

def categorical_feature_scores(df, target, threshold=6):
    cat_cols = df.select_dtypes(include=['object', 'category']).columns
    results = []
    tukey_results = {}

    for col in cat_cols:
        if df[col].isnull().sum() > 0 or df[col].nunique() < 2:
            continue

        groups = [df[df[col] == level][target] for level in df[col].dropna().unique()]
        n_cat = df[col].nunique()

        try:
            if n_cat <= threshold:
                f_stat, p_value = f_oneway(*groups)
                test_type = 'ANOVA'

                # Tukey's HSD post-hoc test
                tukey = pairwise_tukeyhsd(endog=df[target], groups=df[col], alpha=0.05)
                tukey_summary = pd.DataFrame(data=tukey.summary().data[1:], columns=tukey.summary().data[0])
                tukey_results[col] = tukey_summary

            else:
                f_stat, p_value = kruskal(*groups)
                test_type = 'Kruskal-Wallis'

        except Exception as e:
            continue

        results.append({
            'feature': col,
            'f_value': f_stat,
            'p_value': p_value,
            'n_categories': n_cat,
            'test_type': test_type
        })

    return pd.DataFrame(results).sort_values(by='f_value', ascending=False), tukey_results

def select_top_features(df, target, num_top=15):
    num_scores = numerical_feature_scores(df, target)
    cat_scores, tukey = categorical_feature_scores(df, target)

    top_num = num_scores[['feature', 'robust_score']].head(num_top)
    top_cat = cat_scores[cat_scores['p_value'] < 0.05].head(num_top)

    return top_num, top_cat, tukey

